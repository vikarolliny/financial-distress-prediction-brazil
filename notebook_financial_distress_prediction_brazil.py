df = df[df["LABEL"].isin([0, 1])].copy()

indicadores = [
    "A39", "A57", "A61", "A76",
    "A38", "A42", "A69", "A78"
]
indicadores = [c for c in indicadores if c in df.columns]

if not indicadores:
    raise ValueError("Nenhum dos indicadores A39, A57, A61, A76, A38, A42, A69 ou A78 foi encontrado.")

for c in indicadores:
    df[c] = pd.to_numeric(df[c], errors="coerce")

