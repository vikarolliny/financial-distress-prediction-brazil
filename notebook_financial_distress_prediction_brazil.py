# 2. Reproduzir exatamente a regra do alvo da Etapa 03
MAX_GAP_DAYS = 120
HORIZON_DAYS = 365

def recalcular_alvo(tabela):
    registros = []
    for id_, g in tabela.groupby('ID', sort=False):
        g = g.sort_values('QUARTER')
        dates = g['QUARTER'].to_numpy(dtype='datetime64[ns]')
        labels = g['LABEL'].to_numpy(dtype=int)
        indices_evento = np.flatnonzero(labels == 1)
        primeiro_evento = int(indices_evento[0]) if len(indices_evento) else None

        for i in np.flatnonzero(labels == 0):
            t = dates[i]
            dias_evento = None
            if primeiro_evento is not None:
                dias_evento = int((dates[primeiro_evento] - t) / np.timedelta64(1, 'D'))
                if dias_evento <= 0:
                    continue

            if dias_evento is not None and dias_evento <= HORIZON_DAYS:
                gaps = np.diff(dates[i:primeiro_evento+1]).astype('timedelta64[D]').astype(int)
                target = 1 if (gaps.max() if len(gaps) else 0) <= MAX_GAP_DAYS else None
            else:
                limite = t + np.timedelta64(HORIZON_DAYS, 'D')
                fim = int(np.searchsorted(dates, limite, side='left'))
                if fim >= len(dates):
                    target = None
                else:
                    gaps = np.diff(dates[i:fim+1]).astype('timedelta64[D]').astype(int)
                    target = 0 if (gaps.max() if len(gaps) else 0) <= MAX_GAP_DAYS else None

            if target is not None:
                registros.append({
                    'ID':id_,
                    'PERIODO':str(pd.Timestamp(t).to_period('Q')),
                    'TARGET_DISTRESS_12M':target
                })
    return pd.DataFrame(registros)

