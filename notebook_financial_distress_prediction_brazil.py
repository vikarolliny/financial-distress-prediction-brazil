print("Empresas com LABEL=1 observado:", len(eventos))

# Índice para localizar rapidamente uma observação
lookup = {
    (row["ID"], row["QUARTER"]): row
    for _, row in df.iterrows()
}
datas_empresa = df.groupby("ID")["QUARTER"].apply(set).to_dict()
empresas = list(datas_empresa.keys())

rng = np.random.default_rng(42)
registros = []
auditoria = []

# ============================================================
# ETAPA 3 — COMPARAÇÃO EQUILIBRADA
# Para cada empresa com evento:
# - exige os 5 trimestres (lags 4 a 0);
# - exige LABEL=0 nos 4 trimestres anteriores;
# - seleciona até 3 controles com a mesma data de referência;
# - exige LABEL=0 nos 5 trimestres dos controles.
# ============================================================
for empresa_evento, data_evento in eventos.items():

    datas = {
        lag: data_evento - pd.DateOffset(months=3 * lag)
        for lag in range(5)
    }

    if not all(
        (empresa_evento, data) in lookup
        for data in datas.values()
    ):
        auditoria.append({
            "empresa_evento": empresa_evento,
            "data_evento": data_evento,
            "controles_disponiveis": 0,
            "controles_selecionados": 0,
            "status": "Excluída: histórico incompleto da empresa com evento"
        })
        continue

    if any(
        lookup[(empresa_evento, datas[lag])]["LABEL"] != 0
        for lag in [1, 2, 3, 4]
    ):
        auditoria.append({
            "empresa_evento": empresa_evento,
            "data_evento": data_evento,
            "controles_disponiveis": 0,
            "controles_selecionados": 0,
            "status": "Excluída: LABEL=1 antes do trimestre de referência"
        })
        continue

    candidatos = []

    for controle in empresas:
        if controle == empresa_evento:
            continue

        if not all(
            data in datas_empresa[controle]
            for data in datas.values()
        ):
            continue

        if not all(
            lookup[(controle, datas[lag])]["LABEL"] == 0
            for lag in range(5)
        ):
            continue

        candidatos.append(controle)

    n = min(3, len(candidatos))
    selecionados = (
        rng.choice(candidatos, size=n, replace=False).tolist()
        if n else []
    )

    episodio = f"{empresa_evento}_{data_evento:%Y%m%d}"

    # Registrar a empresa com evento
    for lag, data in datas.items():
        row = lookup[(empresa_evento, data)]
        rec = {
            "episodio": episodio,
            "empresa_referencia": empresa_evento,
            "ID": empresa_evento,
            "grupo": "Com evento",
            "data_referencia": data_evento,
            "lag_trimestres": lag
        }
        rec.update({c: row[c] for c in indicadores})
        registros.append(rec)

    # Registrar controles pareados à data do evento
    for controle in selecionados:
        for lag, data in datas.items():
            row = lookup[(controle, data)]
            rec = {
                "episodio": episodio,
                "empresa_referencia": empresa_evento,
                "ID": controle,
                "grupo": "Controle",
                "data_referencia": data_evento,
                "lag_trimestres": lag
            }
            rec.update({c: row[c] for c in indicadores})
            registros.append(rec)

    auditoria.append({
        "empresa_evento": empresa_evento,
        "data_evento": data_evento,
        "controles_disponiveis": len(candidatos),
        "controles_selecionados": n,
        "status": "OK" if n > 0 else "Sem controle elegível"
    })

