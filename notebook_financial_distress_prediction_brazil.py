# Se houver duplicatas conflitantes, interromper para evitar escolhas arbitrárias.
duplicatas = df.duplicated(["ID", "QUARTER"], keep=False)

if duplicatas.any():
    conflitos = (
        df[duplicatas].groupby(["ID", "QUARTER"])["LABEL"]
        .nunique()
    )
    if (conflitos > 1).any():
        raise ValueError(
            "Há empresa/trimestre com LABEL conflitante. "
            "Não é seguro continuar sem resolver essas duplicatas."
        )
    df = df.drop_duplicates(["ID", "QUARTER"], keep="first")

df = df.sort_values(["ID", "QUARTER"])

