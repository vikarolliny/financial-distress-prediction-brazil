import sys, zipfile, hashlib
from pathlib import Path
import numpy as np
import pandas as pd


def auditar(zip_original, csv_painel, csv_alvo, saida='resultados_auditoria_cvm'):
    destino=Path(saida)
    destino.mkdir(parents=True,exist_ok=True)
    with zipfile.ZipFile(zip_original) as z:
        arquivos_csv=[n for n in z.namelist() if n.lower().endswith('.csv')]
        if len(arquivos_csv)!=1:
            raise ValueError(f'Esperado 1 CSV no ZIP original; encontrados: {arquivos_csv}')
        with z.open(arquivos_csv[0]) as f:
            original=pd.read_csv(f)
    painel=pd.read_csv(csv_painel)
    alvo=pd.read_csv(csv_alvo)

    for nome, df, campos in [('Original',original,['ID','QUARTER','LABEL']),('Painel',painel,['ID','QUARTER','LABEL']),('Modelagem',alvo,['ID','QUARTER','LABEL','TARGET_DISTRESS_12M'])]:
        faltantes=set(campos)-set(df.columns)
        if faltantes: raise ValueError(f'{nome}: colunas faltando: {faltantes}')
        df['QUARTER']=pd.to_datetime(df['QUARTER'],errors='raise')
        df['ID']=pd.to_numeric(df['ID'],errors='raise').astype('int64')
        df['LABEL']=pd.to_numeric(df['LABEL'],errors='raise').astype('int64')
        if not df['LABEL'].isin([0,1]).all(): raise ValueError(f'{nome}: LABEL não-binário')
    indicadores=[f'A{i}' for i in range(1,85)]
    for nome, df in [('Original',original),('Painel',painel),('Modelagem',alvo)]:
        ausentes=set(indicadores)-set(df.columns)
        if ausentes: raise ValueError(f'{nome}: indicadores ausentes {sorted(ausentes)}')
    for nome, df in [('Original', original),('Painel',painel),('Modelagem',alvo)]:
        if df.duplicated(['ID','QUARTER']).any():
            raise ValueError(f'{nome}: ID + QUARTER duplicado, rever antes de prosseguir')

    orig_q = original.copy()
    orig_q['TRIMESTRE_CALENDARIO']=orig_q['QUARTER'].dt.to_period('Q').astype(str)
    dup_trimestre=orig_q[orig_q.duplicated(['ID','TRIMESTRE_CALENDARIO'],keep=False)][['ID','QUARTER','TRIMESTRE_CALENDARIO','LABEL']].sort_values(['ID','QUARTER'])
    dup_trimestre.to_csv(destino/'observacoes_repetidas_trimestre.csv',index=False)
    fora_fim=orig_q.loc[~orig_q['QUARTER'].dt.is_quarter_end,['ID','QUARTER','LABEL']].copy()
    fora_fim.to_csv(destino/'datas_fora_fim_trimestre.csv',index=False)

    # Comparação por chave, sem supor que a ordenação das linhas é igual.
    col=['ID','QUARTER','LABEL']+indicadores
    comum=original[col].merge(painel[col],on=['ID','QUARTER'],how='outer',indicator=True,validate='one_to_one',suffixes=('_orig','_painel'))
    retiradas=comum.loc[comum['_merge'].eq('left_only'),['ID','QUARTER','LABEL_orig']].rename(columns={'LABEL_orig':'LABEL'}).copy()
    retiradas.to_csv(destino/'linhas_removidas_na_limpeza.csv',index=False)
    iguais=comum['_merge'].eq('both')
    alterados={}
    for c in ['LABEL']+indicadores:
        a=pd.to_numeric(comum.loc[iguais,c+'_orig'],errors='coerce').to_numpy(dtype=float)
        b=pd.to_numeric(comum.loc[iguais,c+'_painel'],errors='coerce').to_numpy(dtype=float)
        n=int(np.count_nonzero(~np.isclose(a,b,rtol=1e-10,atol=1e-10,equal_nan=True)))
        if n: alterados[c]=n
    # Eventos observados na base original e persistência
    ordenado=painel.sort_values(['ID','QUARTER']).copy()
    ordenado['LABEL_ANTERIOR']=ordenado.groupby('ID')['LABEL'].shift(1)
    transicoes=pd.crosstab(ordenado['LABEL_ANTERIOR'],ordenado['LABEL'],dropna=False)
    transicoes.to_csv(destino/'transicoes_label.csv')
    primeira=ordenado.groupby('ID',sort=True).first()[['LABEL']].rename(columns={'LABEL':'LABEL_NA_ENTRADA'})
    empresas_pos=ordenado.loc[ordenado.LABEL.eq(1),'ID'].nunique()
    eventos_0_1=int(((ordenado.LABEL_ANTERIOR==0)&(ordenado.LABEL==1)).sum())
    eventos_1_0=int(((ordenado.LABEL_ANTERIOR==1)&(ordenado.LABEL==0)).sum())
    eventos_no_inicio=int(primeira.LABEL_NA_ENTRADA.eq(1).sum())
    eventos=ordenado.loc[ordenado.LABEL.eq(1)].groupby('ID')['QUARTER'].min().rename('PRIMEIRO_LABEL_1')
    eventos.to_csv(destino/'datas_primeiro_label_1.csv')

    # Reconstituir TARGET_DISTRESS_12M pelas mesmas regras documentadas
    # na etapa 03: 365 dias e gaps de no máximo 120 dias.
    previstos=[]
    for id_, g in ordenado.groupby('ID',sort=False):
        datas=g['QUARTER'].to_numpy(dtype='datetime64[ns]')
        labs=g['LABEL'].to_numpy(dtype=int)
        pos=np.flatnonzero(labs==1)
        evento=int(pos[0]) if len(pos) else None
        for i in np.flatnonzero(labs==0):
            t=datas[i]
            dias_ate_evento=(int((datas[evento]-t)/np.timedelta64(1,'D')) if evento is not None else None)
            if dias_ate_evento is not None and dias_ate_evento<=0:
                continue
            if dias_ate_evento is not None and dias_ate_evento<=365:
                j=evento
                gaps=np.diff(datas[i:j+1]).astype('timedelta64[D]').astype(int)
                if len(gaps)==0 or gaps.max()<=120:
                    previstos.append((id_,pd.Timestamp(t),1))
            else:
                j=int(np.searchsorted(datas,t+np.timedelta64(365,'D'),side='left'))
                if j<len(datas):
                    gaps=np.diff(datas[i:j+1]).astype('timedelta64[D]').astype(int)
                    if len(gaps)==0 or gaps.max()<=120:
                        previstos.append((id_,pd.Timestamp(t),0))
    recalculado=pd.DataFrame(previstos,columns=['ID','QUARTER','TARGET_RECALCULADO'])
    original_alvo=alvo[['ID','QUARTER','LABEL','TARGET_DISTRESS_12M']].copy()
    original_alvo['TARGET_DISTRESS_12M']=pd.to_numeric(original_alvo['TARGET_DISTRESS_12M'],errors='raise').astype(int)
    confronto=original_alvo.merge(recalculado,on=['ID','QUARTER'],how='outer',indicator=True,validate='one_to_one')
    divergencias=confronto.loc[~confronto['_merge'].eq('both')|(confronto['TARGET_DISTRESS_12M']!=confronto['TARGET_RECALCULADO'])]
    divergencias.to_csv(destino/'divergencias_alvo_12m.csv',index=False)

    stats={
        'observacoes_base_original':len(original),
        'empresas_originais':original.ID.nunique(),
        'positivos_label_original':int(original.LABEL.sum()),
        'negativos_label_original':int(original.LABEL.eq(0).sum()),
        'observacoes_painel':len(painel),
        'observacoes_removidas':int(comum['_merge'].eq('left_only').sum()),
        'observacoes_acrescentadas':int(comum['_merge'].eq('right_only').sum()),
        'celulas_alteradas_nas_linhas_preservadas':sum(alterados.values()),
        'linhas_com_data_nao_fim_trimestre_original':len(fora_fim),
        'pares_repetidos_no_mesmo_trimestre_calendario_original':len(dup_trimestre)//2,
        'empresas_com_label_1':empresas_pos,
        'transicoes_0_para_1':eventos_0_1,
        'transicoes_1_para_0':eventos_1_0,
        'empresas_que_ja_comecam_em_label_1':eventos_no_inicio,
        'linhas_modelagem':len(alvo),
        'positivos_target_12m':int(alvo.TARGET_DISTRESS_12M.sum()),
        'negativos_target_12m':int(alvo.TARGET_DISTRESS_12M.eq(0).sum()),
        'empresas_com_target_positivo':alvo.loc[alvo.TARGET_DISTRESS_12M.eq(1),'ID'].nunique(),
        'linhas_modelagem_com_label_original_diferente_de_zero':int((alvo.LABEL!=0).sum()),
        'linhas_alvo_recalculado':len(recalculado),
        'divergencias_target_12m':len(divergencias),
    }
    pd.DataFrame([{'verificacao':k,'valor':v} for k,v in stats.items()]).to_csv(destino/'resumo_conferencia.csv',index=False)
    with open(destino/'LEIA_ME.txt','w',encoding='utf-8') as f:
        f.write('AUDITORIA REPRODUZÍVEL — CVM\n\n')
        f.write('Fonte: Rubens Marques Chaves, Nonstationary and Imbalanced Dataset for Financial Distress Prediction (2025).\n')
        f.write('GitHub: https://github.com/rubensmchaves/ml-fdp\nIEEE DataPort: https://doi.org/10.21227/x8ry-gz76\n\n')
        f.write('O autor descreve LABEL=0 como normal e LABEL=1 como financial distress.\n')
        f.write('A regra operacional completa de criação de LABEL não está explícita no README.\n')
        f.write('TARGET_DISTRESS_12M é um alvo DERIVADO no projeto, prevendo LABEL=1 futuro nos 365 dias seguintes.\n')
        f.write('Essas verificações testam integridade e correspondência de dados, NÃO validam a definição econômica do LABEL, nem excluem vazamento por regra de rotulagem ou datas de publicação.\n\n')
        for k,v in stats.items(): f.write(f'{k}: {v}\n')
        if alterados: f.write('Indicadores alterados: '+repr(alterados)+'\n')
    pacote=destino.parent/'auditoria_CVM_conferencia_reproduzivel.zip'
    with zipfile.ZipFile(pacote,'w',compression=zipfile.ZIP_DEFLATED) as z:
        for file in sorted(destino.iterdir()):
            if file.is_file(): z.write(file,arcname=file.name)
    print('\nRESULTADO DA CONFERÊNCIA')
    for k,v in stats.items(): print(f'{k}: {v}')
    print('\nPacote de resultados:',pacote)
    return stats, pacote

