def top_k_table(y_true, ids, score, model_name):
    y_arr = np.asarray(y_true, dtype=int)
    ids_arr = np.asarray(ids)
    score_arr = np.asarray(score, dtype=float)
    n_total = len(y_arr)
    total_pos_rows = int(y_arr.sum())
    total_pos_ids = pd.Series(ids_arr[y_arr == 1]).nunique()
    rows = []
    order = np.argsort(-score_arr, kind="mergesort")
    for fraction in [0.01, 0.05, 0.10]:
        n_alerts = max(1, int(np.ceil(n_total * fraction)))
        idx = order[:n_alerts]
        chosen_y, chosen_ids = y_arr[idx], ids_arr[idx]
        positive_ids_captured = pd.Series(chosen_ids[chosen_y == 1]).nunique()
        hits = int(chosen_y.sum())
        rows.append({
            "modelo": model_name,
            "percentual_revisado": fraction,
            "linhas_alertadas": n_alerts,
            "positivos_capturados_linhas": hits,
            "precisao_linhas": hits / n_alerts,
            "recall_linhas": hits / total_pos_rows if total_pos_rows else np.nan,
            "empresas_unicas_na_lista": pd.Series(chosen_ids).nunique(),
            "empresas_com_alvo_positivo_capturadas": positive_ids_captured,
            "empresas_com_alvo_positivo_no_teste": total_pos_ids,
            "recall_empresas_positivas": positive_ids_captured / total_pos_ids if total_pos_ids else np.nan,
            "precisao_aleatoria_linhas": y_arr.mean()
        })
    return rows

